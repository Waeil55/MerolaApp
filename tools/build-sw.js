/* Regenerates sw.js with the full list of app files to precache and a fresh version stamp.
   Run after adding or changing files:  node tools/build-sw.js */
const fs = require("fs");
const path = require("path");
const root = path.join(__dirname, "..");
const files = ["./", "index.html", "styles.css", "manifest.webmanifest"];
// Walk each folder, including the per-grade content folders (content/kg, content/g1 ...).
const walk = (dir) => { for (const f of fs.readdirSync(path.join(root, dir), { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) { const rel = dir + "/" + f.name; if (f.isDirectory()) walk(rel); else if (/\.(js|png|svg)$/.test(f.name)) files.push(rel); } };
for (const dir of ["js", "content", "icons"]) walk(dir);
const version = "gka-" + new Date().toISOString().slice(0, 19).replace(/[-:T]/g, "");
const sw = `/* Genius Kids Academy service worker. Generated by tools/build-sw.js on ${new Date().toISOString()}.
   Precaches every app file so the whole app works offline (network first, cache when offline), and keeps Google Fonts in a runtime cache. */
const VERSION = "${version}";
const PRECACHE = ${JSON.stringify(files, null, 0).replace(/,/g, ", ")};
self.addEventListener("install", (e) => { e.waitUntil(caches.open(VERSION).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting())); });
self.addEventListener("activate", (e) => { e.waitUntil(caches.keys().then((keys) => Promise.all(keys.filter((k) => /^gka-[0-9]/.test(k) && k !== VERSION).map((k) => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener("message", (e) => { if (e.data === "skipWaiting") self.skipWaiting(); });
self.addEventListener("fetch", (e) => {
  const req = e.request; if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (/\/audio\/.+\.mp3$/.test(url.pathname)) return;
  if (url.origin === location.origin) {
    // App files: network first so updates arrive at once; the cache answers when offline or after 3.5 seconds.
    const cacheKey = req.mode === "navigate" ? "./" : req;
    const fromCache = () => caches.match(cacheKey, { ignoreSearch: true }).then((r) => r || caches.match("index.html"));
    const net = fetch(req).then((res) => { if (res && res.ok && req.mode !== "navigate") { const copy = res.clone(); caches.open(VERSION).then((c) => c.put(req, copy)); } return res; });
    const timeout = new Promise((resolve) => setTimeout(resolve, 3500)).then(fromCache);
    e.respondWith(Promise.race([net.catch(fromCache), timeout.then((r) => r || net)]).then((r) => r || fromCache()));
    return;
  }
  if (/fonts\\.(googleapis|gstatic)\\.com$/.test(url.hostname)) {
    // Fonts: stale-while-revalidate so the app never waits on them.
    e.respondWith(caches.open("gka-fonts").then((c) => c.match(req).then((hit) => { const net = fetch(req).then((res) => { if (res && res.ok) c.put(req, res.clone()); return res; }).catch(() => hit); return hit || net; })));
  }
});
`;
fs.writeFileSync(path.join(root, "sw.js"), sw);
console.log("sw.js written:", files.length, "files,", version);
